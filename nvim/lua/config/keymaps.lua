local map = vim.keymap.set
local theme = require("config.theme")

map("n", "<leader>o", function()
  vim.cmd.update()
  dofile(vim.g.dotfiles_nvim_init)
  vim.notify("Neovim config reloaded")
end, { desc = "Reload config" })
map("n", "<leader>w", "<cmd>write<cr>", { desc = "Save" })
map("n", "<leader>q", "<cmd>quit<cr>", { desc = "Quit" })
map("n", "<leader>u", vim.cmd.UndotreeToggle, { desc = "Undo history" })
map("n", "<leader>sf", "<cmd>Pick files<cr>", { desc = "Find files" })
map("n", "<leader>sg", "<cmd>Pick grep_live<cr>", { desc = "Search text" })
map("n", "<leader>s.", "<cmd>Pick visit_paths<cr>", { desc = "Recent files" })
map("n", "<leader>h", "<cmd>Pick help<cr>", { desc = "Help" })
map("n", "<leader>sd", "<cmd>Pick diagnostic<cr>", { desc = "Diagnostics" })
map({ "n", "x" }, "<leader>f", function()
  require("conform").format({ async = true })
end, { desc = "Format buffer or selection" })
map("n", "<leader>st", function()
  vim.ui.select(theme.themes, {
    prompt = "Select theme",
    format_item = function(item)
      return item == vim.g.colors_name and item .. " (current)" or item
    end,
  }, function(choice)
    if choice then
      theme.apply(choice)
    end
  end)
end, { desc = "Select theme" })
map("n", "<leader>tn", function()
  theme.cycle(1)
end, { desc = "Next theme" })
map("n", "<leader>tp", function()
  theme.cycle(-1)
end, { desc = "Previous theme" })
map("n", "<leader>e", vim.diagnostic.open_float, { desc = "Line diagnostics" })
map("n", "<leader>sq", function()
  vim.diagnostic.setqflist({ open = true })
end, { desc = "Diagnostics quickfix list" })
map("n", "gd", vim.lsp.buf.definition, { desc = "Definition" })
map("n", "gD", vim.lsp.buf.declaration, { desc = "Declaration" })
map("n", "gt", vim.lsp.buf.type_definition, { desc = "Type definition" })
map("n", "gr", vim.lsp.buf.references, { desc = "References" })
map("n", "gi", vim.lsp.buf.implementation, { desc = "Implementation" })
map("n", "K", function()
  vim.lsp.buf.hover({ border = "rounded", max_width = 100, max_height = 28, focusable = false })
end, { desc = "Hover documentation" })
map("i", "<C-s>", function()
  vim.lsp.buf.signature_help({ border = "rounded", max_width = 100, max_height = 20, focusable = false })
end, { desc = "Signature help" })
map({ "n", "x" }, "<leader>ca", vim.lsp.buf.code_action, { desc = "Code action" })
map("n", "<leader>rn", vim.lsp.buf.rename, { desc = "Rename symbol" })
map("n", "]d", function()
  vim.diagnostic.jump({ count = 1, float = true })
end, { desc = "Next diagnostic" })
map("n", "[d", function()
  vim.diagnostic.jump({ count = -1, float = true })
end, { desc = "Previous diagnostic" })
map("n", "-", "<cmd>Oil<cr>", { desc = "File browser" })

for key, direction in pairs({ h = "h", j = "j", k = "k", l = "l" }) do
  map("n", "<C-" .. key .. ">", "<C-w>" .. direction, { desc = "Focus split " .. direction })
end
